# ----------------------------------------------------------------------
# 01. Descubre el tipo
# ----------------------------------------------------------------------
#
# Imprime el tipo de `42`, `42.0`, `"42"`, `true`, `'4'` y el resultado
# de `7 / 2`. Explica cada uno.
# ----------------------------------------------------------------------

print(type(42))     # tipo número entero
print(type(42.0))   # tipo número de punto flotante
print(type("42"))   # tipo cadena de caracteres
print(type(True))   # tipo booleano
print(type('4'))    # tipo cadena de caracteres
print(type(7 / 2))  # tipo número de punto flotante
