# ----------------------------------------------------------------------
# 02. Operadores de asignación compuesta
# ----------------------------------------------------------------------
#
# Dado `n = 10`, aplica `+= 5`, `*= 2`, `-= 3`, `%= 4` y registra el
# valor en cada paso.
# ----------------------------------------------------------------------

n = 10
print(n)  # 10

n += 5    # n = n + 5
print(n)  # 15

n *= 2    # n = n * 2
print(n)  # 30

n -= 3    # n = n - 3
print(n)  # 27

n %= 4    # n = n % 4
print(n)  # 3
