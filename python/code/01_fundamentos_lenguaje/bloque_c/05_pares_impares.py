# ----------------------------------------------------------------------
# 05. Pares e impares sin condicionales
# ----------------------------------------------------------------------
#
# Obtén `n % 2` para varios `n` y observa el patrón.
# ----------------------------------------------------------------------

print(4 % 2)   # 0
print(7 % 2)   # 1
print(10 % 2)  # 0
print(15 % 2)  # 1
print(0 % 2)   # 0
print(-3 % 2)  # 1 (en Python)

# Patrón:  n % 2 → 0 (si `n` es par)
#          n % 2 → 1 (si `n` es impar)
