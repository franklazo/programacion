# ----------------------------------------------------------------------
# 03. Promedio de tres notas
# ----------------------------------------------------------------------
#
# Pide tres notas y muestra el promedio con 2 decimales.
# ----------------------------------------------------------------------

n1 = float(input("Nota 1: "))
n2 = float(input("Nota 2: "))
n3 = float(input("Nota 3: "))

promedio = (n1 + n2 + n3) / 3

print(f"El promedio es: {promedio:.2f}")
