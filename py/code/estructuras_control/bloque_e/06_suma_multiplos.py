# Suma de los múltiplos de 3 o 5 menores que 1000 (Project Euler #1).
# ----------------------------------------------------------------------

suma = 0

for i in range(1, 1000):  # 0 a 999
    if i % 3 == 0 or i % 5 == 0:
        suma += i

print(suma)  # 233168
