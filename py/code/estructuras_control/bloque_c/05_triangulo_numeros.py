# Imprimir un triángulo de números (1 / 12 / 123 / ...).
# ----------------------------------------------------------------------

n = int(input("Altura: "))

for i in range(1, n + 1):
    for j in range(1, i + 1):  # imprime de 1 hasta i
        print(j, end=" ")
    print()
